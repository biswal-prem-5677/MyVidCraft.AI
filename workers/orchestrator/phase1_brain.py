from __future__ import annotations

import hashlib
from datetime import date, timedelta

from packages.core.myvidcraft_core.llm_schemas import LLMStrategyPack
from packages.core.myvidcraft_core.schemas import ContentCalendarItem, Platform, StrategyPack

from . import llm

CALENDAR_DAYS = 7
_PLATFORM_ROTATION = [Platform.youtube, Platform.podcast, Platform.youtube_shorts]

_BRAIN_SYSTEM = """You are the content strategist for an AI podcast/video studio.

You produce a strategy pack for a single niche: a slate of candidate topics, a
library of hooks, and a short publishing calendar.

Rules:
- Hooks open with tension, a specific claim, or a curiosity gap. No "In this video".
- Topics are specific and arguable, not generic listicles.
- `hook_score` is your own 0.0-1.0 estimate of scroll-stopping power. Spread the
  scores honestly across the range; do not give everything 0.9.
- `format` is one of: talking_head, audio_episode, explainer, interview.
- Write for the brand's stated tone. Never invent facts about real people.
- Return between 8 and 12 topics, between 8 and 12 hooks, and exactly {days}
  calendar items. Do not include dates; they are assigned by the caller."""


def _stable_float_0_1(seed: str) -> float:
    h = hashlib.sha256(seed.encode("utf-8")).hexdigest()
    return int(h[:8], 16) / 0xFFFFFFFF


def _calendar_dates(days: int, start: date | None = None) -> list[str]:
    start = start or date.today()
    return [str(start + timedelta(days=i)) for i in range(days)]


def generate_strategy(niche: str, brand_profile: dict) -> StrategyPack:
    """
    Produce a StrategyPack for `niche`.

    Tries Claude first; falls back to the deterministic template generator when the
    LLM path is unavailable or fails, so a run always yields a valid artifact.
    """
    pack = _generate_strategy_llm(niche, brand_profile)
    if pack is not None:
        return pack
    return _generate_strategy_template(niche, brand_profile)


def _generate_strategy_llm(niche: str, brand_profile: dict) -> StrategyPack | None:
    brand_tone = str(brand_profile.get("tone") or brand_profile.get("style") or "confident")
    audience = str(brand_profile.get("audience") or "a general but motivated audience")
    taboos = brand_profile.get("taboos") or []
    taboo_line = f"\nAvoid these topics entirely: {', '.join(map(str, taboos))}." if taboos else ""

    user = (
        f"Niche: {niche}\n"
        f"Brand tone: {brand_tone}\n"
        f"Target audience: {audience}\n"
        f"Publishing calendar length: {CALENDAR_DAYS} days."
        f"{taboo_line}\n\n"
        "Produce the strategy pack."
    )

    result = llm.generate_structured(
        system=_BRAIN_SYSTEM.format(days=CALENDAR_DAYS),
        user=user,
        output_format=LLMStrategyPack,
    )
    if result is None:
        return None
    if not result.viral_topic_slate or not result.hook_library or not result.calendar:
        return None

    dates = _calendar_dates(CALENDAR_DAYS)
    calendar = [item.to_domain(dates[i % len(dates)]) for i, item in enumerate(result.calendar[: len(dates)])]

    return StrategyPack(
        niche=niche,
        brand_summary=result.brand_summary.strip() or f"{brand_tone} personal brand in {niche}",
        viral_topic_slate=[t.strip() for t in result.viral_topic_slate if t.strip()],
        hook_library=[h.strip() for h in result.hook_library if h.strip()],
        calendar=calendar,
        notes=[n.strip() for n in result.notes if n.strip()] or ["Generated by the Claude content brain."],
    )


def _generate_strategy_template(niche: str, brand_profile: dict) -> StrategyPack:
    """Offline fallback. Deterministic for a given niche + date."""
    brand_tone = str(brand_profile.get("tone") or brand_profile.get("style") or "confident")
    brand_summary = f"{brand_tone} personal brand in {niche}"

    topic_templates = [
        f"What nobody tells you about {niche}",
        f"The uncomfortable truth about {niche}",
        f"Do this for 7 days in {niche} — results",
        f"{niche}: 5 mistakes beginners keep repeating",
        f"The fastest way to improve your {niche} outcomes",
    ]
    hook_library = [
        f"Stop scrolling — this changes how you think about {niche}.",
        f"If you're serious about {niche}, you need to hear this.",
        f"This is why most people fail at {niche}.",
        f"The 10-second test that predicts your {niche} results.",
        f"Do NOT do this in {niche} — do this instead.",
    ]

    calendar: list[ContentCalendarItem] = []
    for i, date_str in enumerate(_calendar_dates(CALENDAR_DAYS)):
        topic = topic_templates[i % len(topic_templates)]
        hook = hook_library[i % len(hook_library)]
        platform = _PLATFORM_ROTATION[i % len(_PLATFORM_ROTATION)]
        hook_score = 0.55 + 0.4 * _stable_float_0_1(f"{niche}:{hook}:{i}")
        calendar.append(
            ContentCalendarItem(
                date=date_str,
                platform=platform,
                topic=topic,
                hook=hook,
                format="talking_head" if platform != Platform.podcast else "audio_episode",
                cta="Follow for part 2 / save this",
                asset_prompts=[f"Minimal bold text thumbnail: '{topic[:28]}…'"],
                hook_score=min(1.0, max(0.0, hook_score)),
            )
        )

    return StrategyPack(
        niche=niche,
        brand_summary=brand_summary,
        viral_topic_slate=topic_templates,
        hook_library=hook_library,
        calendar=calendar,
        notes=[
            "Offline template strategy (no LLM configured or LLM call failed).",
            "Set MYVIDCRAFT_ANTHROPIC_API_KEY to enable the Claude content brain.",
        ],
    )
