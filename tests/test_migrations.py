"""
The migration chain.

Schema changes stopped being implicit when Alembic landed: `create_all` only ever
*adds*, so a column whose type changed stays stale and silently wrong on every
database that already existed. These tests guard the two ways that goes wrong.

The expensive one to catch late is drift — someone edits a model, the tests pass
because the test database is built by `create_all`, and the mismatch only
surfaces on a deploy against a real database. `test_models_and_migrations_agree`
is the check that fails in CI instead.

Every test runs against its own throwaway SQLite file, so nothing here touches
the configured database.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path

import pytest

alembic_config = pytest.importorskip("alembic.config")
from alembic import command  # noqa: E402
from alembic.autogenerate import compare_metadata  # noqa: E402
from alembic.migration import MigrationContext  # noqa: E402
from alembic.script import ScriptDirectory  # noqa: E402
from sqlalchemy import create_engine  # noqa: E402
from sqlmodel import SQLModel  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]

EXPECTED_TABLES = {"project", "run", "artifact"}


def _config(db_path: Path):
    """An Alembic config pointed at a scratch database."""
    import apps.api.models  # noqa: F401  (registers the tables on SQLModel.metadata)

    cfg = alembic_config.Config(str(ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT / "infra" / "migrations"))
    cfg.set_main_option("sqlalchemy.url", f"sqlite:///{db_path.as_posix()}")
    # env.py reads settings for the URL; this attribute lets it be overridden
    # without mutating process-wide configuration.
    cfg.attributes["sqlalchemy.url"] = f"sqlite:///{db_path.as_posix()}"
    return cfg


@pytest.fixture
def scratch_db(tmp_path, monkeypatch):
    db = tmp_path / "migrations.sqlite3"
    url = f"sqlite:///{db.as_posix()}"
    monkeypatch.setenv("MYVIDCRAFT_DATABASE_URL", url)

    from apps.api import settings as settings_module

    monkeypatch.setattr(settings_module.settings, "database_url", url)
    return db


def _tables(db: Path) -> set[str]:
    with sqlite3.connect(db) as c:
        return {r[0] for r in c.execute("select name from sqlite_master where type='table'")}


def _indexes(db: Path) -> set[str]:
    with sqlite3.connect(db) as c:
        return {r[0] for r in c.execute("select name from sqlite_master where type='index'")}


# -- the chain runs ---------------------------------------------------------


def test_upgrade_builds_every_table(scratch_db):
    command.upgrade(_config(scratch_db), "head")

    assert EXPECTED_TABLES <= _tables(scratch_db)


def test_upgrade_creates_the_query_indexes(scratch_db):
    """Runs are listed by project and status; artifacts by run and type."""
    command.upgrade(_config(scratch_db), "head")

    indexes = _indexes(scratch_db)
    for expected in ("ix_run_project_id", "ix_run_status", "ix_artifact_run_id", "ix_artifact_type"):
        assert expected in indexes


def test_downgrade_removes_the_schema(scratch_db):
    """A downgrade that leaves tables behind makes a rollback unrepeatable."""
    cfg = _config(scratch_db)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")

    assert not (EXPECTED_TABLES & _tables(scratch_db))


def test_upgrade_is_repeatable_after_a_downgrade(scratch_db):
    cfg = _config(scratch_db)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")

    assert EXPECTED_TABLES <= _tables(scratch_db)


# -- the chain is well-formed -----------------------------------------------


def test_there_is_exactly_one_head():
    """
    Two heads mean two people branched the schema and neither merged.

    Alembic will not upgrade past an ambiguous head, so this fails the build
    rather than the deploy.
    """
    script = ScriptDirectory(str(ROOT / "infra" / "migrations"))

    assert len(script.get_heads()) == 1, f"expected one head, found {script.get_heads()}"


def test_every_revision_imports():
    """
    Autogenerated revisions reference `sqlmodel` and `sa.Text` without importing
    them — both fail at import time, and only when the migration is first run.
    """
    script = ScriptDirectory(str(ROOT / "infra" / "migrations"))
    revisions = list(script.walk_revisions())

    assert revisions, "no migrations found"
    for rev in revisions:
        assert rev.module is not None


# -- models and migrations agree --------------------------------------------


def test_models_and_migrations_agree(scratch_db):
    """
    The drift check.

    A model edited without a matching migration passes every other test in the
    suite, because the test database is built by `create_all` from those same
    models. It then fails on the first deploy against a database that was built
    by the migration chain instead. This is that failure, moved into CI.
    """
    import apps.api.models  # noqa: F401

    command.upgrade(_config(scratch_db), "head")

    engine = create_engine(f"sqlite:///{scratch_db.as_posix()}")
    try:
        with engine.connect() as conn:
            ctx = MigrationContext.configure(conn, opts={"compare_type": True})
            diff = compare_metadata(ctx, SQLModel.metadata)
    finally:
        engine.dispose()

    # alembic_version is Alembic's own bookkeeping and is never in the models.
    real = [d for d in diff if "alembic_version" not in str(d)]

    assert not real, f"models and migrations disagree — generate a revision:\n{real}"
